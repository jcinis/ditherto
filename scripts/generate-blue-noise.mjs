// Deterministic toroidal void-and-cluster rank mask, following Ulichney (1993).
// https://cv.ulichney.com/papers/1993-void-cluster.pdf
// This generates our own data; no third-party texture or code is bundled.
import { writeFile } from 'node:fs/promises';
const size=64, count=size*size, sigma=1.5;
let seed=0x6d2b79f5;
function random(){seed^=seed<<13;seed^=seed>>>17;seed^=seed<<5;return (seed>>>0)/4294967296;}
const kernel=[];
for(let y=-6;y<=6;y++) for(let x=-6;x<=6;x++) kernel.push([x,y,Math.exp(-(x*x+y*y)/(2*sigma*sigma))]);
let bits=new Uint8Array(count), energy=new Float64Array(count);
function change(index,value){
 const delta=value-bits[index];bits[index]=value;
 const x=index%size,y=Math.floor(index/size);
 for(const [dx,dy,w] of kernel) energy[((y+dy+size)%size)*size+(x+dx+size)%size]+=delta*w;
}
function extreme(occupied,max){let index=-1,best=max?-Infinity:Infinity;for(let i=0;i<count;i++) if(bits[i]===occupied&&(max?energy[i]>best:energy[i]<best)){index=i;best=energy[i];}return index;}
const shuffled=Array.from({length:count},(_,i)=>i);
for(let i=count-1;i>0;i--){const j=Math.floor(random()*(i+1));[shuffled[i],shuffled[j]]=[shuffled[j],shuffled[i]];}
const initial=Math.floor(count*.1);
for(let i=0;i<initial;i++) change(shuffled[i],1);
let converged=false;
for(let n=0;n<count*20;n++){const cluster=extreme(1,true);change(cluster,0);const voidIndex=extreme(0,false);change(voidIndex,1);if(cluster===voidIndex){converged=true;break;}}
if(!converged) throw new Error('Relaxation did not converge');
const base=bits.slice(), baseEnergy=energy.slice(), ranks=new Uint16Array(count);
for(let rank=initial-1;rank>=0;rank--){const i=extreme(1,true);ranks[i]=rank;change(i,0);}
bits=base.slice();energy=baseEnergy.slice();
for(let rank=initial;rank<count/2;rank++){const i=extreme(0,false);ranks[i]=rank;change(i,1);}
const inverse=bits.map(v=>1-v);bits=new Uint8Array(count);energy=new Float64Array(count);
for(let i=0;i<count;i++) if(inverse[i]) change(i,1);
for(let rank=count/2;rank<count;rank++){const i=extreme(1,true);ranks[i]=rank;change(i,0);}
const rows=Array.from({length:size},(_,y)=>`  ${[...ranks.slice(y*size,(y+1)*size)].join(', ')},`);
await writeFile(new URL('../src/patterns/blueNoise64.ts',import.meta.url),`// Generated by scripts/generate-blue-noise.mjs. Seed 0x6d2b79f5; sigma 1.5; periodic 64×64.\nexport const blueNoiseRanks = new Uint16Array([\n${rows.join('\n')}\n]);\n`);
console.log('Generated 4096 void-and-cluster ranks.');
